"""Monte Carlo (TOPAS / Geant4) Input Deck Generator Tool for OpenRad Agent.

Generates syntactically valid, production-ready TOPAS parameter simulation files
configured for radiation transport, dosimetry scoring, and Bragg peak analysis.
Includes beam energy bounds guardrails (0.01 - 250 MeV).
"""

from typing import List, Optional
from pydantic import BaseModel, Field

from openrad.validation.physics_rules import (
    PhysicsValidationEngine,
    BeamEnergyBoundsError,
)


class TOPASGeneratorInput(BaseModel):
    particle_type: str = Field(description="Particle species: 'proton', 'e-', 'gamma', or 'neutron'.")
    energy_MeV: float = Field(description="Beam energy in MeV.")
    geometry_type: str = Field(
        default="water_phantom",
        description="'water_phantom', 'slab_heterogeneity', or 'ct_patient'.",
    )
    phantom_dimensions_cm: List[float] = Field(
        default=[30.0, 30.0, 30.0],
        description="Dimensions [x, y, z] in cm.",
    )
    number_of_histories: int = Field(
        default=100000,
        description="Total primary histories to simulate.",
    )


def generate_topas_deck(
    particle_type: str,
    energy_MeV: float,
    geometry_type: str = "water_phantom",
    phantom_dimensions_cm: Optional[List[float]] = None,
    number_of_histories: int = 100000,
) -> str:
    """Generates a syntactically valid TOPAS (Geant4-based) parameter file (.txt)

    configured for dose scoring and radiation transport analysis.
    Validates clinical beam energy bounds (0.01 MeV <= E <= 250 MeV).
    """
    if phantom_dimensions_cm is None:
        phantom_dimensions_cm = [30.0, 30.0, 30.0]

    # Normalize particle species
    p_norm = particle_type.strip().lower()
    particle_map = {
        "proton": "proton",
        "protons": "proton",
        "e-": "e-",
        "electron": "e-",
        "electrons": "e-",
        "gamma": "gamma",
        "photon": "gamma",
        "photons": "gamma",
        "xray": "gamma",
        "neutron": "neutron",
        "neutrons": "neutron",
    }
    if p_norm not in particle_map:
        raise ValueError(
            f"Unsupported particle species '{particle_type}'. Allowed: 'proton', 'e-', 'gamma', 'neutron'."
        )
    actual_particle = particle_map[p_norm]

    # 1. Physics Validation: Beam Energy Bounds Check
    PhysicsValidationEngine.validate_beam_energy(
        energy_MeV=energy_MeV,
        particle_type=actual_particle,
        raise_on_fail=True,
    )

    # Validate geometry dimensions
    if len(phantom_dimensions_cm) != 3 or any(d <= 0 for d in phantom_dimensions_cm):
        raise ValueError(f"Phantom dimensions must be 3 positive floats [x, y, z] in cm. Got: {phantom_dimensions_cm}")

    hlx = phantom_dimensions_cm[0] / 2.0
    hly = phantom_dimensions_cm[1] / 2.0
    hlz = phantom_dimensions_cm[2] / 2.0

    world_hlx = max(hlx * 1.5, 40.0)
    world_hly = max(hly * 1.5, 40.0)
    world_hlz = max(hlz * 1.5, 40.0)

    # Physics modules selection
    if actual_particle in ["proton", "neutron"]:
        physics_modules = '5 "g4em-standard_opt4" "g4hadron-elastic" "g4hadron-inelastic" "g4decay" "g4ion-binary-cascade"'
    else:
        physics_modules = '1 "g4em-standard_opt4"'

    # Construct TOPAS parameter deck
    lines = [
        "# ====================================================================",
        "# TOPAS Parameter File Generated by OpenRad Agent",
        f"# Particle: {actual_particle} | Energy: {energy_MeV} MeV | Geometry: {geometry_type}",
        "# ====================================================================",
        "",
        "# --- Global & Threading Settings ---",
        "i:Ts/NumberOfThreads = 0  # Use all available CPU cores",
        "b:Ts/PauseBeforeQuit = \"False\"",
        "s:Ts/DumpNonDefaultFactor = \"True\"",
        "",
        "# --- World Volume ---",
        "s:Ge/World/Type = \"TsBox\"",
        "s:Ge/World/Material = \"Air\"",
        f"d:Ge/World/HLX = {world_hlx:.2f} cm",
        f"d:Ge/World/HLY = {world_hly:.2f} cm",
        f"d:Ge/World/HLZ = {world_hlz:.2f} cm",
        "b:Ge/World/Invisible = \"True\"",
        "",
    ]

    # Geometry Setup
    geom_norm = geometry_type.strip().lower()
    if geom_norm in ["water_phantom", "water"]:
        lines.extend([
            "# --- Water Phantom Geometry ---",
            "s:Ge/Phantom/Type = \"TsBox\"",
            "s:Ge/Phantom/Parent = \"World\"",
            "s:Ge/Phantom/Material = \"G4_WATER\"",
            f"d:Ge/Phantom/HLX = {hlx:.2f} cm",
            f"d:Ge/Phantom/HLY = {hly:.2f} cm",
            f"d:Ge/Phantom/HLZ = {hlz:.2f} cm",
            "d:Ge/Phantom/TransX = 0.0 cm",
            "d:Ge/Phantom/TransY = 0.0 cm",
            "d:Ge/Phantom/TransZ = 0.0 cm",
            "s:Ge/Phantom/Color = \"blue\"",
            "",
        ])
        scorer_component = "Phantom"
    elif geom_norm in ["slab_heterogeneity", "heterogeneity"]:
        slab_thick = phantom_dimensions_cm[2] / 4.0
        lines.extend([
            "# --- Multi-Layer Heterogeneous Phantom ---",
            "s:Ge/Phantom/Type = \"TsBox\"",
            "s:Ge/Phantom/Parent = \"World\"",
            "s:Ge/Phantom/Material = \"Air\"",
            f"d:Ge/Phantom/HLX = {hlx:.2f} cm",
            f"d:Ge/Phantom/HLY = {hly:.2f} cm",
            f"d:Ge/Phantom/HLZ = {hlz:.2f} cm",
            "",
            "# Layer 1: Soft Tissue",
            "s:Ge/Layer1/Type = \"TsBox\"",
            "s:Ge/Layer1/Parent = \"Phantom\"",
            "s:Ge/Layer1/Material = \"G4_TISSUE_SOFT_ICRP\"",
            f"d:Ge/Layer1/HLX = {hlx:.2f} cm",
            f"d:Ge/Layer1/HLY = {hly:.2f} cm",
            f"d:Ge/Layer1/HLZ = {slab_thick/2.0:.2f} cm",
            f"d:Ge/Layer1/TransZ = {-hlz + slab_thick*0.5:.2f} cm",
            "",
            "# Layer 2: Cortical Bone",
            "s:Ge/Layer2/Type = \"TsBox\"",
            "s:Ge/Layer2/Parent = \"Phantom\"",
            "s:Ge/Layer2/Material = \"G4_BONE_CORTICAL_ICRP\"",
            f"d:Ge/Layer2/HLX = {hlx:.2f} cm",
            f"d:Ge/Layer2/HLY = {hly:.2f} cm",
            f"d:Ge/Layer2/HLZ = {slab_thick/2.0:.2f} cm",
            f"d:Ge/Layer2/TransZ = {-hlz + slab_thick*1.5:.2f} cm",
            "",
            "# Layer 3: Lung (Inhale)",
            "s:Ge/Layer3/Type = \"TsBox\"",
            "s:Ge/Layer3/Parent = \"Phantom\"",
            "s:Ge/Layer3/Material = \"G4_LUNG_ICRP\"",
            f"d:Ge/Layer3/HLX = {hlx:.2f} cm",
            f"d:Ge/Layer3/HLY = {hly:.2f} cm",
            f"d:Ge/Layer3/HLZ = {slab_thick/2.0:.2f} cm",
            f"d:Ge/Layer3/TransZ = {-hlz + slab_thick*2.5:.2f} cm",
            "",
            "# Layer 4: Water",
            "s:Ge/Layer4/Type = \"TsBox\"",
            "s:Ge/Layer4/Parent = \"Phantom\"",
            "s:Ge/Layer4/Material = \"G4_WATER\"",
            f"d:Ge/Layer4/HLX = {hlx:.2f} cm",
            f"d:Ge/Layer4/HLY = {hly:.2f} cm",
            f"d:Ge/Layer4/HLZ = {slab_thick/2.0:.2f} cm",
            f"d:Ge/Layer4/TransZ = {-hlz + slab_thick*3.5:.2f} cm",
            "",
        ])
        scorer_component = "Phantom"
    elif geom_norm in ["ct_patient", "patient", "dicom"]:
        lines.extend([
            "# --- Patient DICOM Geometry Container ---",
            "s:Ge/Patient/Type = \"TsBox\"",
            "s:Ge/Patient/Parent = \"World\"",
            "s:Ge/Patient/Material = \"G4_WATER\"",
            f"d:Ge/Patient/HLX = {hlx:.2f} cm",
            f"d:Ge/Patient/HLY = {hly:.2f} cm",
            f"d:Ge/Patient/HLZ = {hlz:.2f} cm",
            "s:Ge/Patient/Color = \"gray\"",
            "# Patient HU to material conversion table is enabled in production clinical setups",
            "",
        ])
        scorer_component = "Patient"
    else:
        raise ValueError(
            f"Unknown geometry_type '{geometry_type}'. Allowed: 'water_phantom', 'slab_heterogeneity', 'ct_patient'."
        )

    # Beam Source Setup
    source_z = -(hlz + 5.0)
    lines.extend([
        "# --- Radiation Beam Source ---",
        "s:So/Beam/Type = \"Beam\"",
        "s:So/Beam/Component = \"BeamPosition\"",
        f"s:So/Beam/BeamParticle = \"{actual_particle}\"",
        f"d:So/Beam/BeamEnergy = {energy_MeV:.4f} MeV",
        "u:So/Beam/BeamEnergySpread = 0.5  # 0.5% energy spread",
        "s:So/Beam/BeamPositionDistribution = \"Gaussian\"",
        "d:So/Beam/BeamPositionCutoffX = 10.0 mm",
        "d:So/Beam/BeamPositionCutoffY = 10.0 mm",
        "s:So/Beam/BeamAngularDistribution = \"None\"",
        f"d:Ge/BeamPosition/TransZ = {source_z:.2f} cm",
        "d:Ge/BeamPosition/RotX = 0.0 deg",
        "",
        "# --- Physics List ---",
        f"sv:Ph/Default/Modules = {physics_modules}",
        "",
        "# --- Scoring ---",
        "s:Sc/DoseScorer/Quantity = \"DoseToMedium\"",
        f"s:Sc/DoseScorer/Component = \"{scorer_component}\"",
        "s:Sc/DoseScorer/OutputFile = \"openrad_dose_scoring\"",
        "s:Sc/DoseScorer/OutputType = \"csv\"",
        "s:Sc/DoseScorer/IfOutputFileAlreadyExists = \"Overwrite\"",
        "i:Sc/DoseScorer/XEBins = 60",
        "i:Sc/DoseScorer/YEBins = 60",
        "i:Sc/DoseScorer/ZEBins = 120",
        "",
        "# --- Run Control ---",
        f"i:So/Beam/NumberOfHistoriesInRun = {int(number_of_histories)}",
    ])

    return "\n".join(lines) + "\n"
